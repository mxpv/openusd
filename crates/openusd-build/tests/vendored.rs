//! The twelve schema libraries OpenUSD ships, generated from the definitions
//! `openusd-schemas` vendors.
//!
//! What the tiny fixture proves about shape, this proves about scale: every
//! kind of declaration upstream actually writes, over six hundred classes, and
//! a registry that answers across all of them at once.

use std::collections::BTreeMap;
use std::path::Path;
use std::{fs, io};

use openusd::usd::{SchemaRegistry, SchemaRegistryBuilder};
use openusd::{tf, vt};
use openusd_build::Views;
use serde_json::Value as Json;

mod common;

use common::{LIBRARIES, configured, schemas};

/// Every library generates, and the twelve compose into one registry: no
/// declaration this crate cannot represent, no name it cannot mint, no
/// collision between the names it does, and a family for each. Each schema's
/// plug info matches the `plugInfo.json` upstream generated beside it.
///
/// One test, because generating the twelve is the expensive part and every
/// question is about the same output.
#[test]
fn every_library_builds_and_registers() {
    let dir = schemas();
    let mut builder = SchemaRegistryBuilder::empty();

    for library in LIBRARIES {
        let output = configured()
            .build_library(dir.join(library).join("schema.usda"), Views::Generate)
            .unwrap_or_else(|error| panic!("{library}: {error}"));

        assert_eq!(output.library_name(), *library);
        assert!(output.views, "{library} generates views");

        builder = output.with_family(|family| builder.register(family));
    }

    let registry = builder.build().expect("the twelve compose");
    let named = |name: &str| tf::Token::from(name);
    assert!(registry.is_a(&named("Sphere"), &named("Gprim")), "a sphere is a gprim");
    assert!(
        registry.is_a(&named("Mesh"), &named("Imageable")),
        "across three levels"
    );
    assert!(
        registry.is_a(&named("SphereLight"), &named("Xformable")),
        "and across libraries"
    );

    let compared: usize = LIBRARIES
        .iter()
        .map(|library| plug_info_matches(&registry, &dir.join(library).join("plugInfo.json")))
        .sum();
    assert!(compared > 0, "the vendored plugInfo.json files carry extra entries");
}

/// Compares each schema's plug info with the `Types` entries of the C++
/// `plugInfo.json` at `path`, the reference C++ reads these entries from,
/// and answers how many entries matched. A library that vendors no
/// `plugInfo.json` has nothing to compare.
///
/// A `Types` entry holds the keys `usdGenSchema` writes itself and the
/// `extraPlugInfo` entries the schema's plug info carries. Every extra entry
/// upstream ships is a bool.
fn plug_info_matches(registry: &SchemaRegistry, path: &Path) -> usize {
    // Every key `usdGenSchema` may write (`usdGenSchema.py:1498-1529,
    // 1597-1621`). No vendored `extraPlugInfo` reuses one, so a key here in a
    // `Types` entry is one the generator wrote.
    const GENERATED: &[&str] = &[
        "bases",
        "autoGenerated",
        "schemaKind",
        "schemaIdentifier",
        "alias",
        "apiSchemaAutoApplyTo",
        "apiSchemaCanOnlyApplyTo",
        "apiSchemaAllowedInstanceNames",
        "apiSchemaInstances",
    ];
    let text = match fs::read_to_string(path) {
        Ok(text) => text,
        Err(error) if error.kind() == io::ErrorKind::NotFound => return 0,
        Err(error) => panic!("{path:?}: {error}"),
    };
    // `plugInfo.json` allows `#` comment lines, which JSON does not.
    let json: Vec<&str> = text
        .lines()
        .filter(|line| !line.trim_start().starts_with('#'))
        .collect();
    let root: Json = serde_json::from_str(&json.join("\n")).unwrap_or_else(|error| panic!("{path:?}: {error}"));

    let mut compared = 0;
    for plugin in root["Plugins"].as_array().expect("a Plugins array") {
        let Some(types) = plugin["Info"]["Types"].as_object() else {
            continue;
        };
        for (cpp_name, entry) in types {
            // A plugin's other types, such as a parser, are no schema.
            let Some(identifier) = entry["schemaIdentifier"].as_str() else {
                continue;
            };
            let expected: BTreeMap<&str, vt::Value> = entry
                .as_object()
                .expect("a type entry is an object")
                .iter()
                .filter(|(key, _)| !GENERATED.contains(&key.as_str()))
                .map(|(key, value)| {
                    let flag = value.as_bool().unwrap_or_else(|| panic!("{cpp_name}.{key} is a bool"));
                    (key.as_str(), vt::Value::Bool(flag))
                })
                .collect();
            let actual: BTreeMap<&str, vt::Value> = registry
                .schema_info(&tf::Token::from(identifier))
                .unwrap_or_else(|| panic!("{identifier} is registered"))
                .plug_info()
                .iter()
                .map(|(key, value)| (key.as_str(), value.clone()))
                .collect();
            assert_eq!(actual, expected, "{cpp_name}");
            compared += expected.len();
        }
    }
    compared
}
