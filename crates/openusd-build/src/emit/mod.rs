/// One library's generated file, `schema` naming what it came from.
///
/// With [`Views::Skip`] it carries the tokens and the schema data alone, which is
/// what a library asking for `skipCodeGeneration` wants and what a crate whose
/// API is written by hand asks for through
/// [`Builder::schema_data`](crate::Builder::schema_data). The data is not
/// optional either way: it is what a registry is built from, so a file without
/// it would leave the schemas unregisterable.
pub fn emit(
    model: &Library,
    externs: &Externs,
    schema: &str,
    views: Views,
    enums: &[TokenEnum],
) -> Result<String, Error> {
    let lowered = match views {
        Views::Generate => lower::library(model, externs, enums)?,
        Views::Skip => lower::tokens(model, enums)?,
    };
    let declarations = decl::with_family(model, family::declarations)?;
    render(emitter::library(&lowered, &declarations), schema)
}

/// The items the generated file declares at its top level, by name.
///
/// [`emitter`] and [`family`] write them under these names and [`lower`]
/// refuses a schema that would reach one, so the two cannot disagree about what
/// is taken: a name added or renamed here changes both.
pub(super) mod items {
    /// The module holding the token constants.
    pub const TOKENS: &str = "tokens";
    /// The constant naming the library.
    pub const LIBRARY_NAME: &str = "LIBRARY_NAME";
    /// The constant holding the declarations a registry takes.
    pub const SCHEMAS: &str = "SCHEMAS";

    /// All of them, for the collision check.
    pub const ALL: [&str; 3] = [TOKENS, LIBRARY_NAME, SCHEMAS];
}

/// One generated item, by the name it is written under.
fn ident(name: &str) -> Ident {
    Ident::new(name, Span::call_site())
}

/// A path as a reader writes it, segment by segment.
///
/// `quote!` spaces a path's tokens apart, and documentation needs the spelling
/// a reader would type.
fn path_text(path: &syn::Path) -> String {
    let leading = match path.leading_colon.is_some() {
        true => "::",
        false => "",
    };
    let segments: Vec<String> = path.segments.iter().map(|segment| segment.ident.to_string()).collect();
    format!("{leading}{}", segments.join("::"))
}

/// An item of the module at `home`, as a reader writes it: `home::name`.
fn within(home: &syn::Path, name: &str) -> String {
    format!("{}::{name}", path_text(home))
}

/// The header every generated file opens with, as upstream marks its own.
const GENERATED_BY: &str = "WARNING: THIS FILE IS GENERATED BY openusd-build. DO NOT EDIT.";

/// The tokens as a formatted file, with the header above them.
///
/// Each top-level item is laid out on its own so that a blank line falls
/// between them: `prettyplease` reads a syntax tree, which has no blank lines of
/// its own to keep.
fn render(file: TokenStream, schema: &str) -> Result<String, Error> {
    let parsed: syn::File = syn::parse2(file).map_err(|cause| Error::Malformed {
        schema: schema.to_owned(),
        cause: cause.to_string(),
    })?;
    let items: Vec<String> = parsed
        .items
        .into_iter()
        .map(|item| {
            let one = syn::File {
                shebang: None,
                frontmatter: None,
                attrs: Vec::new(),
                items: vec![item],
            };
            prettyplease::unparse(&one)
        })
        .collect();

    Ok(format!(
        "// {GENERATED_BY}\n// Generated from {schema}.\n\n{}",
        items.join("\n")
    ))
}

