//! The Rust a schema library is generated as.
//!
//! [`lower`] settles every name a schema implies — what each type and trait is
//! called, which traits a view implements, which accessors it offers — and is
//! the only place that does, so a name is decided once and can be checked for
//! collisions there. [`emitter`] writes the views from that, [`family`] writes
//! the schema data from the declarations beside it, and [`render`] lays the
//! result out as text.
//!
//! The file is written to be included bare into whatever module a consumer
//! chooses, through `openusd::include_schema!`. That is what decides its shape:
//! it carries no `use` block, since one would apply to the module it lands in
//! and could collide with what the consumer already imports, so every path in it
//! is spelled in full.

